export type Shape = 'circle' | 'triangle' | 'square' | 'diamond' | 'pentagon' | 'star' | 'cross';

export interface StationDef {
  name: string;
  lon: number;
  lat: number;
  tier: 1 | 2 | 3;
  shape?: Shape;
}

export interface CityDef {
  id: string; // adcode as in GeoJSON
  name: string;
  short: string;
  color: string;
  stations: StationDef[];
  startUnlocked?: boolean;
}

const S = (name: string, lon: number, lat: number, tier: 1 | 2 | 3 = 1, shape?: Shape): StationDef => ({
  name,
  lon,
  lat,
  tier,
  shape,
});

